#!/usr/bin/env python3
"""Generate the semantic build-id header used by board replay records."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


MATERIAL = "\n".join(
    [
        "genome_contract=uart_sampler_v2_headroom@2.0.0",
        "variant=pbil_island8_graded_v9",
        "benchmark_id=uart_stream_v2_headroom",
        "benchmark_numeric_band=v2_graded_m1_setb",
        "train_frames=64",
        "holdout_frames=256",
        "seed_policy=compile_time_or_recorded",
    ]
).encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("sw/autoehw_build_id.h"))
    args = parser.parse_args()

    digest = hashlib.sha256(MATERIAL).digest()
    value = int.from_bytes(digest[:8], "little")
    lo = value & 0xFFFFFFFF
    hi = (value >> 32) & 0xFFFFFFFF
    text = f"""#ifndef AUTOEHW_BUILD_ID_H
#define AUTOEHW_BUILD_ID_H

/* Generated by scripts/gen_autoehw_build_id.py.
 * This is a semantic replay build id, not a hash of the firmware image.
 */
#define AUTOEHW_BUILD_ID_LO 0x{lo:08X}u
#define AUTOEHW_BUILD_ID_HI 0x{hi:08X}u

#endif
"""
    args.out.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
